# Shared by every test below: generic glue that links whatever ZigDeps generated and runs it.
# Nothing here is package-specific, so a single build.zig/consumer shape covers all scenarios.
_BUILD_ZIG = textwrap.dedent("""
    const std = @import("std");
    const conan_setup = @import("conan_zig_deps/conan_setup.zig");

    pub fn build(b: *std.Build) void {
        const target = b.standardTargetOptions(.{});
        const optimize = b.standardOptimizeOption(.{});

        const mod = b.createModule(.{ .target = target, .optimize = optimize });
        mod.addCSourceFile(.{ .file = b.path("main.c"), .flags = &.{} });
        mod.link_libc = true;

        const exe = b.addExecutable(.{ .name = "app", .root_module = mod });
        conan_setup.linkDependencies(mod);
        b.installArtifact(exe);

        const run_cmd = b.addRunArtifact(exe);
        run_cmd.step.dependOn(b.getInstallStep());
        const run_step = b.step("run", "Run the app");
        run_step.dependOn(&run_cmd.step);
    }
    """)


def _app_conanfile(requires):
    # ``settings`` matters here beyond package_id: VirtualRunEnv reads settings.os to decide
    # whether to export (DY)LD_LIBRARY_PATH at all, so a consumer that declares no settings
    # gets an empty conanrun environment and its shared dependencies stay unfindable.
    return textwrap.dedent("""
        from conan import ConanFile

        class App(ConanFile):
            settings = "os", "compiler", "build_type", "arch"
            requires = "%s"
            generators = "ZigDeps"

            def build(self):
                # ZigDeps only wires dependencies up for the *build*; making shared libraries
                # loadable at *run* time is Conan's job, through the auto-generated conanrun
                # environment (PATH on Windows, (DY)LD_LIBRARY_PATH elsewhere). Same idiom as
                # test_cps.py and test_cmakeconfigdeps_new_cpp_linkage.py.
                self.run("zig build run", env="conanrun")
        """) % requires


def _main_c(function_name):
    return textwrap.dedent("""
        #include <stdio.h>
        extern int %s(void);
        int main(void) {
            printf("%s=%%d\\n", %s());
            return 0;
        }
        """) % (function_name, function_name, function_name)


def _build_zig_single_target(target_name):
    """ Like _BUILD_ZIG, but calls linkDependency() for one specific target directly instead
    of linkDependencies() - which would link every direct dependency wholesale """
    return textwrap.dedent("""
        const std = @import("std");
        const conan_setup = @import("conan_zig_deps/conan_setup.zig");

        pub fn build(b: *std.Build) void {
            const target = b.standardTargetOptions(.{});
            const optimize = b.standardOptimizeOption(.{});

            const mod = b.createModule(.{ .target = target, .optimize = optimize });
            mod.addCSourceFile(.{ .file = b.path("main.c"), .flags = &.{} });
            mod.link_libc = true;

            const exe = b.addExecutable(.{ .name = "app", .root_module = mod });
            conan_setup.linkDependency(mod, "%s");
            b.installArtifact(exe);

            const run_cmd = b.addRunArtifact(exe);
            run_cmd.step.dependOn(b.getInstallStep());
            const run_step = b.step("run", "Run the app");
            run_step.dependOn(&run_cmd.step);
        }
        """) % target_name


# Conan's Windows binaries are built with MSVC, but Zig defaults to the MinGW (gnu) ABI on
# Windows - and only ships libc for that ABI. Linking an MSVC-produced object in gnu mode
# fails on the /DEFAULTLIB:MSVCRT and /DEFAULTLIB:OLDNAMES directives it carries, which lld
# then looks for under MinGW names (libMSVCRT.a). Tests whose dependencies are built by
# CMake - i.e. by MSVC on Windows - therefore have to ask for the matching ABI. Tests that
# build their dependencies with `zig cc` do not: those are gnu on both sides already.
_BUILD_ZIG_MATCHING_CONAN_ABI = _BUILD_ZIG.replace(
    'const std = @import("std");',
    'const std = @import("std");\nconst builtin = @import("builtin");', 1
).replace(
    "    const target = b.standardTargetOptions(.{});",
    "    // Match the ABI of the Conan binaries: MSVC on Windows, native elsewhere.\n"
    "    var query: std.Target.Query = .{};\n"
    "    if (builtin.os.tag == .windows) query.abi = .msvc;\n"
    "    const target = b.standardTargetOptions(.{ .default_target = query });", 1)


@pytest.mark.slow
@pytest.mark.tool("zig")
def test_zigdeps():
    """ A real ``zig build`` links a Conan static-library dependency (with 2 components,
    one requiring the other) through the glue generated by ZigDeps, and runs successfully """
    c = TestClient()
    liba_conanfile = textwrap.dedent("""
        import os
        from conan import ConanFile
        from conan.tools.files import copy

        class LibA(ConanFile):
            name = "liba"
            version = "1.0"
            package_type = "static-library"
            exports_sources = "comp1.c", "comp1.h", "comp2.c", "comp2.h"

            def build(self):
                self.run("zig cc -c comp1.c -o comp1.o")
                self.run("zig cc -c comp2.c -o comp2.o")
                self.run("zig ar rcs libcomp1.a comp1.o")
                self.run("zig ar rcs libcomp2.a comp2.o")

            def package(self):
                copy(self, "*.a", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.h", self.build_folder, os.path.join(self.package_folder, "include"))

            def package_info(self):
                self.cpp_info.components["comp1"].libs = ["comp1"]
                self.cpp_info.components["comp1"].requires = ["comp2"]
                self.cpp_info.components["comp2"].libs = ["comp2"]
        """)
    comp1_h = 'int comp1_value(void);\n'
    comp1_c = textwrap.dedent("""
        extern int comp2_value(void);
        int comp1_value(void) { return comp2_value() + 1; }
        """)
    comp2_h = 'int comp2_value(void);\n'
    comp2_c = 'int comp2_value(void) { return 41; }\n'

    c.save({"liba/conanfile.py": liba_conanfile,
            "liba/comp1.h": comp1_h,
            "liba/comp1.c": comp1_c,
            "liba/comp2.h": comp2_h,
            "liba/comp2.c": comp2_c,
            "conanfile.py": _app_conanfile("liba/1.0"),
            "build.zig": _BUILD_ZIG,
            "main.c": _main_c("comp1_value")})
    c.run("create liba")
    c.run("build .")
    assert "comp1_value=42" in c.out


