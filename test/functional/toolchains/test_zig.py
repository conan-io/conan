@pytest.mark.slow
@pytest.mark.tool("zig")
def test_zigdeps_cpp_runtime_can_be_opted_out():
    """ link_libc/link_libcpp are ?bool in Zig, where null means "not decided", so ZigDeps
    only fills them in when the consumer has not. Setting link_libcpp explicitly therefore
    wins regardless of whether it comes before or after linkDependencies().

    Checked by building for real and looking at what Zig was actually told to link, rather
    than at the text of the generated file. """
    c = TestClient()
    # A C package: with `languages` unset it is assumed to be C++, so the C++ runtime is
    # requested for it - which is exactly what the consumer may want to undo.
    pkg = textwrap.dedent("""
        import os
        from conan import ConanFile
        from conan.tools.files import copy

        class Pkg(ConanFile):
            name = "cpkg"
            version = "1.0"
            package_type = "static-library"
            exports_sources = "val.c", "val.h"

            def build(self):
                self.run("zig cc -c val.c -o val.o")
                self.run("zig ar rcs libval.a val.o")

            def package(self):
                copy(self, "*.a", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.h", self.build_folder, os.path.join(self.package_folder, "include"))

            def package_info(self):
                self.cpp_info.libs = ["val"]
        """)
    build_zig = textwrap.dedent("""
        const std = @import("std");
        const conan = @import("conan_zig_deps/conan_setup.zig");

        pub fn build(b: *std.Build) void {
            const mod = b.createModule(.{
                .root_source_file = b.path("main.zig"),
                .target = b.standardTargetOptions(.{}),
                .optimize = b.standardOptimizeOption(.{}),
            });
            %s
            const exe = b.addExecutable(.{ .name = "app", .root_module = mod });
            b.installArtifact(exe);
        }
        """)
    main_zig = textwrap.dedent("""
        const std = @import("std");
        const c = @cImport({ @cInclude("val.h"); });
        pub fn main() void { std.debug.print("{d}\\n", .{c.val()}); }
        """)
    app = textwrap.dedent("""
        from conan import ConanFile

        class App(ConanFile):
            settings = "os", "compiler", "build_type", "arch"
            requires = "cpkg/1.0"
            generators = "ZigDeps"

            def build(self):
                self.run("zig build --verbose", env="conanrun")
        """)

    c.save({"cpkg/conanfile.py": pkg,
            "cpkg/val.h": "int val(void);\n",
            "cpkg/val.c": "int val(void) { return 7; }\n",
            "conanfile.py": app,
            "main.zig": main_zig})
    c.run("create cpkg")

    def linked_libcpp(link_block):
        c.save({"build.zig": build_zig % link_block})
        c.run("build .")
        # --verbose prints the compile command; look at what Zig was actually asked to link
        return any(" -lc++" in line for line in c.out.splitlines())

    assert linked_libcpp("conan.linkDependencies(mod);") is True
    assert linked_libcpp("conan.linkDependencies(mod);\n            "
                         "mod.link_libcpp = false;") is False
    # …and opting out first must not be overwritten by the generator
    assert linked_libcpp("mod.link_libcpp = false;\n            "
                         "conan.linkDependencies(mod);") is False
