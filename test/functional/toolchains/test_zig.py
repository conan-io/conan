def _shared_ext():
    system = platform.system()
    if system == "Darwin":
        return ".dylib"
    if system == "Windows":
        return ".dll"
    return ".so"


def _shared_link_flags(libname):
    """ Platform-specific flags a shared library needs at link time: an ``@rpath`` install
    name on Darwin (what Conan packages normally carry, and what ``DYLD_LIBRARY_PATH`` from
    conanrun resolves by leaf name), a soname on Linux/ELF as the equivalent, and an explicit
    import library on Windows (LLD's MinGW-compatible COFF linker, unlike a plain ELF/Mach-O
    link, doesn't produce one unless asked - matching the .a naming Conan's own
    auto-deduction regex expects) """
    system = platform.system()
    if system == "Darwin":
        return "-install_name @rpath/lib%s%s" % (libname, _shared_ext())
    if system == "Windows":
        return "-Wl,--out-implib,lib%s.a" % libname
    return "-Wl,-soname,lib%s%s" % (libname, _shared_ext())


def _export_header(libname, function_name):
    """ A portable dllexport/dllimport header for a shared library built directly with
    ``zig cc``: on Windows, symbols aren't exported by default (unlike CMake's
    WINDOWS_EXPORT_ALL_SYMBOLS), so the .c file defining ``function_name`` must be compiled
    with ``-D<libname>_EXPORTS`` (matching CMake's own auto-defined macro name) for this to
    resolve to dllexport there; any other translation unit merely consuming the header
    (without that define) correctly sees dllimport instead """
    return textwrap.dedent("""
        #if defined(_WIN32) && defined(%s_EXPORTS)
        #define %s_API __declspec(dllexport)
        #elif defined(_WIN32)
        #define %s_API __declspec(dllimport)
        #else
        #define %s_API
        #endif
        %s_API int %s(void);
        """) % (libname, libname.upper(), libname.upper(), libname.upper(),
               libname.upper(), function_name)


@pytest.mark.slow
@pytest.mark.tool("zig")
def test_zigdeps_shared_chain():
    """ A chain of two shared libraries (shareda -> sharedb): both get linked, and both are
    found at runtime through conanrun rather than through anything the generator emits """
    c = TestClient()
    ext = _shared_ext()
    sharedb_conanfile = textwrap.dedent("""
        import os
        from conan import ConanFile
        from conan.tools.files import copy

        class SharedB(ConanFile):
            name = "sharedb"
            version = "1.0"
            package_type = "shared-library"
            exports_sources = "sharedb.c", "sharedb.h"

            def build(self):
                self.run("zig cc -shared -fPIC -Dsharedb_EXPORTS %s -o libsharedb%s sharedb.c")

            def package(self):
                # Split by pattern, not by platform: the runtime-loadable file (.so/.dylib/
                # .dll) goes to bindirs on Windows (where Conan's own auto-deduction looks
                # for it) and libdirs everywhere else; any import library (.a, Windows-only
                # here) always goes to libdirs. Harmless no-ops for the patterns that don't
                # apply to the current platform.
                copy(self, "*.dll", self.build_folder, os.path.join(self.package_folder, "bin"))
                copy(self, "*.so*", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.dylib", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.a", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.h", self.build_folder, os.path.join(self.package_folder, "include"))

            def package_info(self):
                self.cpp_info.libs = ["sharedb"]
        """) % (_shared_link_flags("sharedb"), ext)
    shareda_conanfile = textwrap.dedent("""
        import os
        from conan import ConanFile
        from conan.tools.files import copy

        class SharedA(ConanFile):
            name = "shareda"
            version = "1.0"
            package_type = "shared-library"
            requires = "sharedb/1.0"
            exports_sources = "shareda.c", "shareda.h"

            def build(self):
                dep = self.dependencies["sharedb"].cpp_info
                self.run('zig cc -c -Dshareda_EXPORTS shareda.c -I"'
                         + dep.includedirs[0] + '" -o shareda.o')
                self.run('zig cc -shared -fPIC %s -o libshareda%s shareda.o -L"'
                         + dep.libdirs[0] + '" -lsharedb')

            def package(self):
                copy(self, "*.dll", self.build_folder, os.path.join(self.package_folder, "bin"))
                copy(self, "*.so*", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.dylib", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.a", self.build_folder, os.path.join(self.package_folder, "lib"))
                copy(self, "*.h", self.build_folder, os.path.join(self.package_folder, "include"))

            def package_info(self):
                self.cpp_info.libs = ["shareda"]
        """) % (_shared_link_flags("shareda"), ext)

    sharedb_h = _export_header("sharedb", "shared_b_value")
    sharedb_c = textwrap.dedent("""
        #include "sharedb.h"
        int shared_b_value(void) { return 10; }
        """)
    shareda_h = _export_header("shareda", "shared_a_value")
    shareda_c = textwrap.dedent("""
        #include "shareda.h"
        #include "sharedb.h"
        int shared_a_value(void) { return shared_b_value() + 1; }
        """)

    c.save({"sharedb/conanfile.py": sharedb_conanfile,
            "sharedb/sharedb.h": sharedb_h,
            "sharedb/sharedb.c": sharedb_c,
            "shareda/conanfile.py": shareda_conanfile,
            "shareda/shareda.h": shareda_h,
            "shareda/shareda.c": shareda_c,
            "conanfile.py": _app_conanfile("shareda/1.0"),
            "build.zig": _BUILD_ZIG,
            "main.c": _main_c("shared_a_value")})
    c.run("create sharedb")
    c.run("create shareda")
    c.run("build .")
    assert "shared_a_value=11" in c.out


