import os
import platform
import shutil
import textwrap

import pytest

from conan.test.assets.sources import gen_function_cpp, gen_function_h
from conan.test.utils.test_files import temp_folder
from conan.test.utils.tools import TestClient


@pytest.mark.slow
@pytest.mark.skipif(platform.system() != "Darwin", reason="Only for Darwin")
@pytest.mark.tool("bazel", "8.x")
def test_bazel_simple_cross_compilation():
    """
    Cross-building Macos x86_64 -> Macos armv8 (or the other way around) with the platforms
    and the C/C++ toolchain generated by BazelToolchain:

    * MODULE.bazel registers the Conan toolchain with include("//conan:conan_toolchain.MODULE.bazel")
    * conan_bzl.rc (used automatically by the Bazel helper) selects the target and host platforms
    """
    build_arch = "armv8" if platform.machine() == "arm64" else "x86_64"
    host_arch = "x86_64" if build_arch == "armv8" else "armv8"
    profile = textwrap.dedent("""
    [settings]
    arch={}
    build_type=Release
    compiler=apple-clang
    compiler.cppstd=gnu17
    compiler.libcxx=libc++
    compiler.version=13.0
    os=Macos
    """)
    conanfile = textwrap.dedent("""
    from conan import ConanFile
    from conan.tools.google import Bazel, bazel_layout

    class MyappConan(ConanFile):
        name = "myapp"
        version = "1.0"
        settings = "os", "compiler", "build_type", "arch"
        generators = "BazelToolchain"

        def layout(self):
            bazel_layout(self)

        def build(self):
            bazel = Bazel(self)
            bazel.build()
    """)
    module = textwrap.dedent("""\
    bazel_dep(name = "rules_cc", version = "0.2.17")
    bazel_dep(name = "platforms", version = "1.1.0")
    include("//conan:conan_toolchain.MODULE.bazel")
    """)
    build = textwrap.dedent("""\
    load("@rules_cc//cc:cc_library.bzl", "cc_library")

    cc_library(
        name = "myapp",
        srcs = ["myapp.cpp"],
        hdrs = ["myapp.h"],
    )
    """)
    client = TestClient(path_with_spaces=False)
    bazel_root_dir = temp_folder(path_with_spaces=False).replace("\\", "/")
    client.save({
        "profile_build": profile.format(build_arch),
        "profile_host": profile.format(host_arch),
        "conanfile.py": conanfile,
        "MODULE.bazel": module,
        ".bazelrc": f"startup --output_user_root={bazel_root_dir}",
        "main/BUILD": build,
        "main/myapp.cpp": gen_function_cpp(name="myapp"),
        "main/myapp.h": gen_function_h(name="myapp"),
    })
    client.run("build . -pr:h profile_host -pr:b profile_build")

    bazel_host_cpu = {"armv8": "aarch64", "x86_64": "x86_64"}[host_arch]
    bazel_build_cpu = {"armv8": "aarch64", "x86_64": "x86_64"}[build_arch]
    # Cross-building: the target and host platforms are passed via the conan_bzl.rc file
    bazelrc = client.load("conan/conan_bzl.rc")
    assert "build:conan-config --platforms=//conan/conan_toolchain:host_platform" in bazelrc
    assert "build:conan-config --host_platform=//conan/conan_toolchain:build_platform" in bazelrc
    assert "--config=conan-config" in client.out
    toolchain_build = client.load("conan/conan_toolchain/BUILD.bazel")
    assert f"@platforms//cpu:{bazel_host_cpu}" in toolchain_build
    assert f"@platforms//cpu:{bazel_build_cpu}" in toolchain_build
    assert 'register_toolchains("//conan/conan_toolchain:cc_toolchain")' in \
           client.load("conan/conan_toolchain.MODULE.bazel")

    libmyapp = os.path.join(client.current_folder, "bazel-bin", "main", "libmyapp.a")
    client.run_command(f'lipo -info {libmyapp}')
    expected_arch = {"armv8": "arm64", "x86_64": "x86_64"}[host_arch]
    assert f"architecture: {expected_arch}" in client.out


def _linux_cross_target():
    """ Returns (conan_arch, gnu_triplet, readelf_machine) of the other Linux architecture """
    if platform.machine() in ("aarch64", "arm64"):
        return "x86_64", "x86_64-linux-gnu", "X86-64"
    return "armv8", "aarch64-linux-gnu", "AArch64"


@pytest.mark.slow
@pytest.mark.skipif(platform.system() != "Linux" or
                    shutil.which(f"{_linux_cross_target()[1]}-gcc") is None,
                    reason="Needs a Linux GCC cross-compiler (crossbuild-essential-xxx)")
@pytest.mark.tool("bazel", "8.x")
def test_bazel_linux_gcc_cross_compilation():
    """
    Cross-building Linux aarch64 <-> x86_64 with the GNU cross-compilers, building a library
    and an executable linking it, with the cc_toolchain generated by BazelToolchain
    """
    host_arch, triplet, machine = _linux_cross_target()
    build_arch = "armv8" if host_arch == "x86_64" else "x86_64"
    profile = textwrap.dedent("""
    [settings]
    arch={}
    build_type=Release
    compiler=gcc
    compiler.cppstd=gnu17
    compiler.libcxx=libstdc++11
    compiler.version=13
    os=Linux
    """)
    profile_host = profile.format(host_arch) + textwrap.dedent(f"""
    [conf]
    tools.build:compiler_executables={{"c": "{triplet}-gcc", "cpp": "{triplet}-g++"}}
    [buildenv]
    AR={triplet}-ar
    STRIP={triplet}-strip
    """)
    conanfile = textwrap.dedent("""
    from conan import ConanFile
    from conan.tools.google import Bazel, bazel_layout

    class MyappConan(ConanFile):
        name = "myapp"
        version = "1.0"
        settings = "os", "compiler", "build_type", "arch"
        generators = "BazelToolchain"

        def layout(self):
            bazel_layout(self)

        def build(self):
            bazel = Bazel(self)
            bazel.build(target="//main:app")
    """)
    module = textwrap.dedent("""\
    bazel_dep(name = "rules_cc", version = "0.2.17")
    bazel_dep(name = "platforms", version = "1.1.0")
    include("//conan:conan_toolchain.MODULE.bazel")
    """)
    build = textwrap.dedent("""\
    load("@rules_cc//cc:cc_binary.bzl", "cc_binary")
    load("@rules_cc//cc:cc_library.bzl", "cc_library")

    cc_library(
        name = "myapp",
        srcs = ["myapp.cpp"],
        hdrs = ["myapp.h"],
    )

    cc_binary(
        name = "app",
        srcs = ["main.cpp"],
        deps = [":myapp"],
    )
    """)
    client = TestClient(path_with_spaces=False)
    bazel_root_dir = temp_folder(path_with_spaces=False).replace("\\", "/")
    client.save({
        "profile_build": profile.format(build_arch),
        "profile_host": profile_host,
        "conanfile.py": conanfile,
        "MODULE.bazel": module,
        ".bazelrc": f"startup --output_user_root={bazel_root_dir}",
        "main/BUILD": build,
        "main/myapp.cpp": gen_function_cpp(name="myapp"),
        "main/myapp.h": gen_function_h(name="myapp"),
        "main/main.cpp": gen_function_cpp(name="main", includes=["myapp"], calls=["myapp"]),
    })
    client.run("build . -pr:h profile_host -pr:b profile_build")
    assert "--config=conan-config" in client.out
    toolchain_build = client.load("conan/conan_toolchain/BUILD.bazel")
    assert f'"gcc": "{shutil.which(f"{triplet}-gcc")}"' in toolchain_build

    app = os.path.join(client.current_folder, "bazel-bin", "main", "app")
    client.run_command(f"readelf -h {app}")
    assert machine in client.out
